#!/usr/bin/env node
// Builds the pinned, self-hosted cubing.js scramble bundle in ../../vendor/cubing.
//
// The browser loads vendor/cubing/scramble.js as a plain ES module. esbuild is
// only a build tool: it resolves cubing's internal chunks and its one bare
// runtime dependency (`random-uint-below`), and it emits the Web Worker chunk.
//
// Run from this folder:  npm ci && npm run build
import { build } from "esbuild";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..");
const vendorDir = path.join(repoRoot, "vendor", "cubing");
const pkg = JSON.parse(fs.readFileSync(path.join(here, "package.json"), "utf8"));

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
const toUrlPath = (rel) => rel.split(path.sep).join("/");

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "lucent-cubing-"));
const entryOut = "scramble";

try {
  const result = await build({
    absWorkingDir: here,
    entryPoints: [{ in: path.join(here, "entry.js"), out: entryOut }],
    outdir: tmp,
    metafile: true,
    bundle: true,
    splitting: true,
    format: "esm",
    entryNames: "[name]",
    chunkNames: "chunks/[name]-[hash]",
    minify: true,
    legalComments: "eof",
    target: "es2022",
    logLevel: "warning",
  });

  const emitted = walk(tmp).filter((file) => file.endsWith(".js"));
  if (!emitted.length) throw new Error("esbuild emitted no JavaScript");
  const entryFile = path.join(tmp, entryOut + ".js");
  if (!fs.existsSync(entryFile)) throw new Error("entry file was not emitted");

  const specifierPattern = /(?:\bfrom\s*|\bimport\s*\(\s*)["']([^"']+)["']/g;
  const urls = [];
  let totalBytes = 0;

  for (const file of emitted) {
    totalBytes += fs.statSync(file).size;
    const source = fs.readFileSync(file, "utf8");
    specifierPattern.lastIndex = 0;
    let match;
    while ((match = specifierPattern.exec(source))) {
      const specifier = match[1];
      if (!specifier.startsWith(".")) {
        throw new Error(`${path.relative(tmp, file)} has a non-local import: ${specifier}`);
      }
      const target = path.resolve(path.dirname(file), specifier);
      if (!target.startsWith(tmp + path.sep) || !fs.existsSync(target)) {
        throw new Error(`${path.relative(tmp, file)} imports a missing file: ${specifier}`);
      }
    }
    if (/sourceMappingURL/.test(source)) throw new Error(`${path.relative(tmp, file)} has a source map reference`);
    urls.push("./vendor/cubing/" + toUrlPath(path.relative(tmp, file)));
  }

  const workerChunk = emitted.find((file) => path.basename(file).startsWith("search-worker-entry-"));
  if (!workerChunk) throw new Error("the cubing search worker chunk was not emitted");
  const workerName = path.basename(workerChunk);
  if (!emitted.some((file) => fs.readFileSync(file, "utf8").includes(workerName))) {
    throw new Error(`no emitted file references the worker chunk (${workerName})`);
  }

  const licenceSource = emitted.find((file) => fs.readFileSync(file, "utf8").includes("Copyright 2019 Google LLC"));
  if (!licenceSource) throw new Error("the bundled Apache-2.0 licence notice was dropped");

  // Replace only generated runtime files; licence/readme files are maintained separately.
  fs.rmSync(path.join(vendorDir, "chunks"), { recursive: true, force: true });
  fs.rmSync(path.join(vendorDir, entryOut + ".js"), { force: true });
  fs.mkdirSync(vendorDir, { recursive: true });
  fs.cpSync(path.join(tmp, "chunks"), path.join(vendorDir, "chunks"), { recursive: true });
  fs.copyFileSync(entryFile, path.join(vendorDir, entryOut + ".js"));

  urls.sort((a, b) => (a === "./vendor/cubing/scramble.js" ? -1 : b === "./vendor/cubing/scramble.js" ? 1 : a.localeCompare(b)));

  const assetsFile = path.join(vendorDir, "assets.js");
  fs.writeFileSync(
    assetsFile,
    [
      "// Generated by tools/cubing-vendor/build.mjs. Do not edit by hand.",
      `// Runtime files for the locally bundled cubing.js ${pkg.dependencies.cubing} scramble generator.`,
      "// sw.js loads this file with importScripts() and adds every entry to the offline precache.",
      "self.CUBING_ASSETS = " + JSON.stringify(urls, null, 2) + ";",
      "",
    ].join("\n"),
  );

  const manifest = {
    package: "cubing",
    version: pkg.dependencies.cubing,
    entry: "./vendor/cubing/scramble.js",
    workerChunk: "./vendor/cubing/chunks/" + workerName,
    assetCount: urls.length,
    totalBytes,
    builtWith: { esbuild: pkg.devDependencies.esbuild, format: "esm", minify: true, target: "es2022" },
    inputs: Object.keys(result.metafile.inputs).sort(),
    files: urls.map((url) => {
      const rel = url.slice("./vendor/cubing/".length);
      return { path: url, bytes: fs.statSync(path.join(vendorDir, rel)).size };
    }),
  };
  fs.writeFileSync(path.join(vendorDir, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

  console.log(`cubing ${manifest.version} bundle written to vendor/cubing`);
  console.log(`entry:  ${manifest.entry}`);
  console.log(`worker: ${manifest.workerChunk}`);
  console.log(`assets: ${manifest.assetCount} files, ${totalBytes} bytes (${(totalBytes / 1024 / 1024).toFixed(2)} MiB)`);
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
